def test_the_hash_detector_sees_a_run_and_stops_at_a_blank_line(tmp_path: Path) -> None:
    """Positive control. A detector that cannot see its own violation is worse than none."""
    path = tmp_path / "sample.py"
    lines = ["# one", "# two", "# three", "", "# four", "x = 1  # trailing, out of scope"]
    found = _own_line_runs(path, lines, "#", "hash_run", [])
    assert [comment.span for comment in found] == [3, 1]


def test_the_hash_detector_ignores_a_hash_inside_a_multiline_string() -> None:
    """The false positive worth excluding by PARSING rather than by loosening the scan."""
    source = 'X = """\n# not a comment\n# still not\n# nor this\n"""\n'
    tree = ast.parse(source)
    found = _own_line_runs(
        Path("sample.py"), source.splitlines(), "#", "hash_run", _multiline_string_ranges(tree)
    )
    assert found == []


def test_the_slash_and_block_detectors_do_not_double_count_or_eat_a_url() -> None:
    """`//` inside a `/* */` must not count twice, and a URL is not a comment."""
    source = "/*\n * a\n * b\n */\nconst u = 'https://example.com/a//b';\n// tail\n// tail two\n"
    blocks, ranges = _block_comments(Path("sample.ts"), source)
    assert [comment.span for comment in blocks] == [4]
    slashes = _own_line_runs(Path("sample.ts"), source.splitlines(), "//", "slash_run", ranges)
    assert [comment.span for comment in slashes] == [2]


def test_the_yaml_header_takes_the_module_cap_and_a_later_run_does_not(tmp_path: Path) -> None:
    """Positive control on the two YAML tiers — a header is a file's decisions, a run is a why."""
    lines = ["# one", "# two", "", "jobs:", "  # three", "  # four"]
    found = _yaml_runs(tmp_path / "sample.yml", lines)
    assert [(comment.tier, comment.cap, comment.span) for comment in found] == [
        ("module", MODULE_DOCSTRING_CAP, 2),
        ("plain", CAP, 2),
    ]


def test_the_workflows_are_in_scope_so_a_regrown_comment_run_is_caught() -> None:
    """`.github/` was out of scope twice over, by root and by suffix — hence two long runs."""
    scoped = {_relative(path) for path in scoped_files()}
