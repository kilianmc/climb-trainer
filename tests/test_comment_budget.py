"""No comment may outgrow its tier's cap unless the allowlist names it with a reason.
Prose is the one thing in this repo nothing else checks: `ruff`, `tsc` and every other gate read
right past a forty-line docstring that stopped being true three PRs ago. A long comment is allowed,
but only with a signature next to it. **What it CANNOT catch:** whether the content is worth its
length, or whether it is true — a green run means "every exception is registered", never "the
comments are good".

The allowlist is `tests/comment_budget_allowlist.toml`, anchored on CONTENT and QUALNAMES, never
line numbers; five staleness arms below make an unearned entry a hard failure.
"""

import ast
import tomllib
from dataclasses import dataclass, replace
from datetime import date
from pathlib import Path
from typing import Final

import pytest

from server.settings import ROOT

ALLOWLIST_PATH: Final = ROOT / "tests" / "comment_budget_allowlist.toml"

# The caps, by tier. Two lines is enough for "why", which is the only thing a comment owes.
CAP: Final = 2
# Module docstrings get more: they are the one place a file's decisions may be written out.
MODULE_DOCSTRING_CAP: Final = 10
# Wire-contract docstrings get the most: FastAPI ships them to API consumers as the OpenAPI
# `description`, so their audience is outside this repo and cannot read the code instead.
WIRE_CONTRACT_CAP: Final = 20

CAPS: Final = {"module": MODULE_DOCSTRING_CAP, "wire": WIRE_CONTRACT_CAP, "plain": CAP}

# The ratchet. Entries whose reason starts with BASELINE are the un-reviewed backlog; new
# comments obey the cap from day one, so this number may only ever go DOWN. Lower it in the
# same PR that trims the comments — never raise it.
BASELINE_RATCHET: Final = 990

# The DEADLINE. The ratchet stops the backlog GROWING; nothing stops it sitting, and a register
# where every row still reads "not yet reviewed" a year from now is a freeze, not a cleanup. Each
# milestone is a date and the most BASELINE rows that may remain once it has passed: green until
# the date, then hard red until the count is at or below the target. The last target is 0, so the
# backlog has an end rather than a floor.
#
# ⚠️ **Editing a number cannot buy silence, by construction.** A target may never exceed
# `BASELINE_RATCHET - MILESTONE_MIN_CUT`, the ratchet may only ever go DOWN, and the ratchet may
# not sit more than 25 above the real count (`test_the_ratchet_is_not_slack`). `MILESTONE_MIN_CUT`
# is deliberately larger than that 25, so raising a target far enough to matter would mean raising
# the ratchet further than its own arm allows. The only move left is trimming comments.
BASELINE_DEADLINE: Final = (
    (date(2026, 12, 1), 800),
    (date(2027, 3, 1), 550),
    (date(2027, 6, 1), 275),
    (date(2027, 9, 1), 0),
)
# Larger than the ratchet's 25 of permitted slack, so the ratchet's own arm is what refuses an
# inflated target rather than this one having to guess at a motive.
MILESTONE_MIN_CUT: Final = 150

# Minimum characters of a real reason. "legacy" is not a register entry.
MIN_REASON_LENGTH: Final = 40
# Minimum characters of an anchor, so a short phrase cannot match half the file.
MIN_ANCHOR_LENGTH: Final = 30

SCOPE: Final = ("server", "migrations", "tests", "web/src", ".github")
KINDS: Final = ("hash_run", "docstring", "slash_run", "block")
# `.github/` is in scope for its workflows: a `#` run there is prose nothing else in the gate
# reads, which is how 15- and 28-line runs grew in two files no cap applied to.
YAML_SUFFIXES: Final = {".yml", ".yaml"}
SCOPED_SUFFIXES: Final = {".py", ".ts", ".tsx"} | YAML_SUFFIXES

# Detected by MARKER, not by path: a path list rots the moment a generator's output moves,
# whereas the marker travels with the file. Two generators, two spellings — TanStack Router
# writes its own banner and would overwrite anything we put there.
GENERATED_MARKERS: Final = (
    "GENERATED FILE — do not edit by hand.",
    "This file was automatically generated by TanStack Router.",
)
GENERATED_MARKER_SCAN_LINES: Final = 40
# Pinned so a third generated file has to be added here deliberately instead of appearing —
# and silently exempting itself from every comment rule in the repo.
GENERATED_FILE_COUNT: Final = 2


@dataclass(frozen=True, slots=True)
class Comment:
    """One comment found by one detector. `anchor` is the FULL normalised identity."""

    path: str
    kind: str
    anchor: str
    span: int
    line: int
    tier: str

    @property
    def cap(self) -> int:
        return CAPS[self.tier]


@dataclass(frozen=True, slots=True)
class Entry:
    """One allowlist row. `anchor` is a PREFIX of a `Comment.anchor`."""

    path: str
    kind: str
    anchor: str
    limit: int
    reason: str


# ---------------------------------------------------------------------------------
# Normalisation and anchoring
# ---------------------------------------------------------------------------------
#
# Line numbers are forbidden as anchors: every entry would rot on the next unrelated edit
# above it, and a register that rots is a register nobody reads. So comment runs anchor on
# their own CONTENT with markers, punctuation and whitespace collapsed away (a typo fix or a
# reflow must not orphan the entry), and docstrings anchor on the dotted qualname — which
# survives any move and breaks only on a RENAME, exactly when the exception wants re-reading.


def normalise(text: str) -> str:
    """Markers, punctuation and whitespace collapsed; lowercased. Unicode-aware."""
    kept = [character if character.isalnum() else " " for character in text]
    return " ".join("".join(kept).split()).lower()


def anchor_prefix(anchor: str) -> str:
    """The shortest whole-word prefix of `anchor` reaching MIN_ANCHOR_LENGTH."""
    prefix = ""
    for word in anchor.split():
        prefix = f"{prefix} {word}".strip()
        if len(prefix) >= MIN_ANCHOR_LENGTH:
            break
    return prefix


# ---------------------------------------------------------------------------------
# File scope
# ---------------------------------------------------------------------------------


def _is_generated(path: Path) -> bool:
    head = "\n".join(path.read_text(encoding="utf-8").splitlines()[:GENERATED_MARKER_SCAN_LINES])
    return any(marker in head for marker in GENERATED_MARKERS)


def _candidates() -> list[Path]:
    found: list[Path] = []
    for root in SCOPE:
        for path in sorted((ROOT / root).rglob("*")):
            if not path.is_file() or "__pycache__" in path.parts:
                continue
            if path.suffix not in SCOPED_SUFFIXES:
                continue
            found.append(path)
    return found


def generated_files() -> list[Path]:
    return [path for path in _candidates() if _is_generated(path)]


def scoped_files() -> list[Path]:
    return [path for path in _candidates() if not _is_generated(path)]


def _relative(path: Path) -> str:
    """Repo-relative, but tolerant: the meta-guards below feed it synthetic paths."""
    if path.is_absolute() and path.is_relative_to(ROOT):
        return path.relative_to(ROOT).as_posix()
    return path.as_posix()


def _dotted(path: Path) -> str:
    return ".".join(Path(_relative(path)).with_suffix("").parts)


# ---------------------------------------------------------------------------------
# Wire contracts — detected BY SHAPE, not by file
# ---------------------------------------------------------------------------------
#
# Exempting the whole of `server/**/routes.py` would over-exempt by half: those files hold far
# more long docstrings than they hold wire contracts. The shape is what earns the bigger cap —
# a `@router.<verb>(...)` decorator, or a `BaseModel` base — because that is what puts the
# docstring in the OpenAPI document where an outside consumer reads it.


def _is_router_decorated(node: ast.FunctionDef | ast.AsyncFunctionDef) -> bool:
    for decorator in node.decorator_list:
        if not isinstance(decorator, ast.Call):
            continue
        func = decorator.func
        if isinstance(func, ast.Attribute) and isinstance(func.value, ast.Name):
            if func.value.id.endswith("router"):
                return True
    return False


def _is_base_model(node: ast.ClassDef) -> bool:
    for base in node.bases:
        if isinstance(base, ast.Name) and base.id == "BaseModel":
            return True
        if isinstance(base, ast.Attribute) and base.attr == "BaseModel":
            return True
    return False


# ---------------------------------------------------------------------------------
# The four detectors
# ---------------------------------------------------------------------------------


def _docstrings(path: Path, tree: ast.Module) -> tuple[list[Comment], list[range]]:
    """Docstring comments, plus the line ranges they occupy (so `#` runs can skip them)."""
    module = _dotted(path)
    is_routes = path.name == "routes.py" and path.parts[-3] == "server"
    comments: list[Comment] = []
    ranges: list[range] = []

    def walk(node: ast.AST, qualname: str) -> None:
        body = getattr(node, "body", None)
        if isinstance(node, ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
            if ast.get_docstring(node, clean=False) is not None and body:
                literal = body[0]
                assert literal.end_lineno is not None
                # Span from the source positions, not the string value: that is exactly the
                # block of lines a reader scrolls past, quotes included.
                span = literal.end_lineno - literal.lineno + 1
                ranges.append(range(literal.lineno, literal.end_lineno + 1))
                tier = "plain"
                if isinstance(node, ast.Module):
                    tier = "module"
                elif is_routes and (
                    _is_base_model(node)
                    if isinstance(node, ast.ClassDef)
                    else _is_router_decorated(node)
                ):
                    tier = "wire"
                comments.append(
                    Comment(_relative(path), "docstring", qualname, span, literal.lineno, tier)
                )
        for child in ast.iter_child_nodes(node):
            if isinstance(child, ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
                walk(child, f"{qualname}.{child.name}")
            elif not isinstance(child, ast.Module):
                walk(child, qualname)

    walk(tree, module)
    return comments, ranges


def _multiline_string_ranges(tree: ast.Module) -> list[range]:
    """Every string literal spanning more than one line — a `#` inside one is not a comment."""
    ranges: list[range] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            if node.end_lineno is not None and node.end_lineno > node.lineno:
                ranges.append(range(node.lineno, node.end_lineno + 1))
    return ranges


def _own_line_runs(
    path: Path, lines: list[str], marker: str, kind: str, excluded: list[range]
) -> list[Comment]:
    """Consecutive lines whose `strip()` starts with `marker`. A blank line ends a run.

    Own-line only: a trailing comment after code is out of scope, because it cannot run long
    without the code running long with it.
    """
    skip = {number for span in excluded for number in span}
    comments: list[Comment] = []
    run: list[str] = []
    start = 0
    for number, raw in enumerate(lines, start=1):
        stripped = raw.strip()
        if stripped.startswith(marker) and number not in skip:
            if not run:
                start = number
            run.append(stripped)
            continue
        if run:
            comments.append(
                Comment(_relative(path), kind, normalise(" ".join(run)), len(run), start, "plain")
            )
            run = []
    if run:
        comments.append(
            Comment(_relative(path), kind, normalise(" ".join(run)), len(run), start, "plain")
        )
    return comments


def _yaml_runs(path: Path, lines: list[str]) -> list[Comment]:
    """Line 1 starts the FILE HEADER, which takes the module cap; every other run is plain."""
    runs = _own_line_runs(path, lines, "#", "hash_run", [])
    return [replace(run, tier="module") if run.line == 1 else run for run in runs]


def _block_comments(path: Path, source: str) -> tuple[list[Comment], list[range]]:
    """`/* ... */`, JSDoc included. Span is newlines + 1.

    Boundary handling follows `web/src/test/sourceScan.ts` — the non-greedy `[\\s\\S]*?` to the
    first `*/`. A string literal containing `/*` is a known false positive and takes an
    allowlist entry; loosening the scan to dodge it would blind the detector.
    """
    comments: list[Comment] = []
    ranges: list[range] = []
    index = 0
    while (open_at := source.find("/*", index)) != -1:
        close_at = source.find("*/", open_at + 2)
        if close_at == -1:
            break
        body = source[open_at : close_at + 2]
        span = body.count("\n") + 1
        first = source.count("\n", 0, open_at) + 1
        comments.append(Comment(_relative(path), "block", normalise(body), span, first, "plain"))
        ranges.append(range(first, first + span))
        index = close_at + 2
    return comments, ranges


def collect() -> list[Comment]:
    """Every comment in scope, from all four detectors."""
    comments: list[Comment] = []
    for path in scoped_files():
        source = path.read_text(encoding="utf-8")
        lines = source.splitlines()
        if path.suffix == ".py":
            tree = ast.parse(source, filename=str(path))
            docstrings, docstring_ranges = _docstrings(path, tree)
            comments.extend(docstrings)
            excluded = docstring_ranges + _multiline_string_ranges(tree)
            comments.extend(_own_line_runs(path, lines, "#", "hash_run", excluded))
        elif path.suffix in YAML_SUFFIXES:
            comments.extend(_yaml_runs(path, lines))
        else:
            blocks, block_ranges = _block_comments(path, source)
            comments.extend(blocks)
            comments.extend(_own_line_runs(path, lines, "//", "slash_run", block_ranges))
    return comments


def over_cap() -> list[Comment]:
    return [comment for comment in collect() if comment.span > comment.cap]


# ---------------------------------------------------------------------------------
# The allowlist
# ---------------------------------------------------------------------------------


def entries() -> list[Entry]:
    with ALLOWLIST_PATH.open("rb") as handle:
        document = tomllib.load(handle)
    rows = document.get("exception", [])
    assert isinstance(rows, list), "the allowlist must be a list of [[exception]] tables"
    return [
        Entry(
            path=str(row["path"]),
            kind=str(row["kind"]),
            anchor=str(row["anchor"]),
            limit=int(row["limit"]),
            reason=str(row["reason"]),
        )
        for row in rows
    ]


def _matches(entry: Entry, comments: list[Comment]) -> list[Comment]:
    return [
        comment
        for comment in comments
        if comment.path == entry.path
        and comment.kind == entry.kind
        and (
            comment.anchor == entry.anchor
            if entry.kind == "docstring"
            else comment.anchor.startswith(entry.anchor)
        )
    ]


@pytest.fixture(scope="module")
def comments() -> list[Comment]:
    return collect()


@pytest.fixture(scope="module")
def allowlist() -> list[Entry]:
    return entries()


