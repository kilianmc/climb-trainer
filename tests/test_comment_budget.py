def test_no_comment_exceeds_its_cap_without_an_allowlist_entry(
    comments: list[Comment], allowlist: list[Entry]
) -> None:
    """The budget itself. Trim the comment, or register it with a reason."""
    registered = {
        (comment.path, comment.kind, comment.anchor)
        for entry in allowlist
        for comment in _matches(entry, comments)
    }
    unregistered = [
        comment
        for comment in comments
        if comment.span > comment.cap
        and (comment.path, comment.kind, comment.anchor) not in registered
    ]
    formatted = "\n".join(
        f"  {comment.path}:{comment.line} {comment.kind} ({comment.tier} tier) "
        f"{comment.span} lines > cap {comment.cap}"
        for comment in unregistered[:20]
    )
    assert not unregistered, (
        f"{len(unregistered)} comment(s) are over their cap with no allowlist entry. Trim them, "
        f"or add an [[exception]] to tests/comment_budget_allowlist.toml with a real reason:\n"
        f"{formatted}"
    )


def test_every_allowlisted_comment_is_within_its_declared_limit(
    comments: list[Comment], allowlist: list[Entry]
) -> None:
    """`limit` is a CEILING, never an equality — an exact match would fire on a typo fix."""
    breached = [
        (entry, comment)
        for entry in allowlist
        for comment in _matches(entry, comments)
        if comment.span > entry.limit
    ]
    formatted = "\n".join(
        f"  {entry.path} {entry.kind} '{entry.anchor[:40]}...' grew to {comment.span} "
        f"lines, limit {entry.limit}"
        for entry, comment in breached[:20]
    )
    assert not breached, (
        f"{len(breached)} allowlisted comment(s) grew past their declared limit. An exception "
        f"is for a comment that is already long, not a licence to keep going:\n{formatted}"
    )


# ---------------------------------------------------------------------------------
# The five staleness arms — the allowlist must not be allowed to rot
# ---------------------------------------------------------------------------------
#
# An allowlist nobody can be wrong about is an allowlist nobody re-reads. Every arm below is a
# HARD failure, because the failure mode being prevented is the register slowly turning into a
# list of comments that no longer exist.


def test_no_allowlist_anchor_resolves_to_nothing(
    comments: list[Comment], allowlist: list[Entry]
) -> None:
    """Arm 1. The comment was deleted or reworded past its anchor; the entry must go too."""
    orphans = [entry for entry in allowlist if not _matches(entry, comments)]
    formatted = "\n".join(f"  {entry.path} {entry.kind} '{entry.anchor}'" for entry in orphans[:20])
    assert not orphans, (
        f"{len(orphans)} allowlist entry(ies) match no comment. Either the comment is gone — "
        f"delete the entry — or it was reworded and the entry needs re-reading, not "
        f"re-anchoring on autopilot:\n{formatted}"
    )


def test_no_allowlist_entry_covers_a_comment_that_is_now_within_its_cap(
    comments: list[Comment], allowlist: list[Entry]
) -> None:
    """Arm 2. It was trimmed. The exception is no longer earned and stops being a licence."""
    earned = [
        (entry, comment)
        for entry in allowlist
        for comment in _matches(entry, comments)
        if comment.span <= comment.cap
    ]
    formatted = "\n".join(
        f"  {entry.path} {entry.kind} '{entry.anchor[:40]}' is now {comment.span} "
        f"lines (cap {comment.cap})"
        for entry, comment in earned[:20]
    )
    assert not earned, (
        f"{len(earned)} allowlist entry(ies) cover a comment that now fits its cap. Someone "
        f"did the work — delete the entry so the cap applies again:\n{formatted}"
    )


def test_no_allowlist_anchor_is_ambiguous(comments: list[Comment], allowlist: list[Entry]) -> None:
    """Arm 3. Two matches means the entry exempts a comment nobody reviewed."""
    ambiguous = [(entry, _matches(entry, comments)) for entry in allowlist]
    ambiguous = [(entry, found) for entry, found in ambiguous if len(found) > 1]
    formatted = "\n".join(
        f"  {entry.path} {entry.kind} '{entry.anchor}' matches {len(found)} comments "
        f"(lines {[comment.line for comment in found]})"
        for entry, found in ambiguous[:20]
    )
    assert not ambiguous, (
        f"{len(ambiguous)} allowlist anchor(s) match more than one comment, so each exempts "
        f"something that was never reviewed. Lengthen the anchor:\n{formatted}"
    )


def test_every_allowlist_entry_carries_a_real_reason(allowlist: list[Entry]) -> None:
    """Arm 4. An allowlist reading "legacy" is not a register, it is a rubber stamp."""
    thin = [entry for entry in allowlist if len(entry.reason.strip()) < MIN_REASON_LENGTH]
    formatted = "\n".join(f"  {entry.path} {entry.kind}: {entry.reason!r}" for entry in thin[:20])
    assert not thin, (
        f"{len(thin)} allowlist entry(ies) have a reason under {MIN_REASON_LENGTH} characters. "
        f"Say what the length buys and who reads it:\n{formatted}"
    )


def test_the_baseline_backlog_only_shrinks(allowlist: list[Entry]) -> None:
    """Arm 5, the ratchet. New comments obey the cap; the backlog is one-way."""
    baseline = [entry for entry in allowlist if entry.reason.startswith("BASELINE")]
    assert len(baseline) <= BASELINE_RATCHET, (
        f"{len(baseline)} BASELINE entries, ratchet is {BASELINE_RATCHET}. A new comment over "
        f"the cap must be trimmed or given a real reason — it may not join the backlog."
    )


def test_the_ratchet_is_not_slack(allowlist: list[Entry]) -> None:
    """The ratchet has to be PINNED to reality, or arm 5 stops meaning anything.

    Left loose, `BASELINE_RATCHET` would drift upward as a matter of course. Requiring it to
    track the real count within a small margin means burning down the backlog and lowering the
    number happen in the same diff.
    """
    baseline = [entry for entry in allowlist if entry.reason.startswith("BASELINE")]
    assert BASELINE_RATCHET - len(baseline) <= 25, (
        f"BASELINE_RATCHET is {BASELINE_RATCHET} but only {len(baseline)} entries remain. "
        f"Lower the ratchet in this PR — slack in it is a comment budget nobody is holding to."
    )


def _milestones_due(count: int, today: date) -> list[tuple[date, int]]:
    """Milestones whose date has arrived and whose target `count` still exceeds."""
    return [(due, target) for due, target in BASELINE_DEADLINE if today >= due and count > target]


def test_the_baseline_backlog_is_burned_down_on_schedule(allowlist: list[Entry]) -> None:
    """The deadline. A backlog the ratchet has merely frozen is not a backlog being cleared."""
    baseline = [entry for entry in allowlist if entry.reason.startswith("BASELINE")]
    due = _milestones_due(len(baseline), date.today())
    formatted = "\n".join(
        f"  by {when.isoformat()}: at most {target} BASELINE rows — "
        f"trim or justify {len(baseline) - target} more"
        for when, target in due
    )
    assert not due, (
        f"{len(baseline)} BASELINE rows remain and a burn-down milestone has passed. Trim the "
        f"comments, or replace the BASELINE reason with a real one, until the count fits:\n"
        f"{formatted}"
    )


def test_the_deadline_schedule_demands_a_real_cut() -> None:
    """The deadline's anti-slack arm: a target nobody has to meet is a date, not a deadline."""
    dates = [due for due, _ in BASELINE_DEADLINE]
    targets = [target for _, target in BASELINE_DEADLINE]
    assert dates == sorted(set(dates)), "milestones must be in strictly increasing date order"
    assert targets == sorted(set(targets), reverse=True), "each target must be below the last"
    assert targets[-1] == 0, "the final milestone must retire the backlog, not park it"
    assert targets[0] <= BASELINE_RATCHET - MILESTONE_MIN_CUT, (
        f"the first target is {targets[0]}, which is not {MILESTONE_MIN_CUT} below the ratchet "
        f"({BASELINE_RATCHET}). Raising a target only works by raising the ratchet, which "
        f"test_the_ratchet_is_not_slack refuses — lower the target instead."
    )


def test_the_deadline_arm_goes_red_once_a_milestone_has_passed() -> None:
    """Positive control. A deadline nobody has watched fire is a deadline nobody should trust."""
    first_due, first_target = BASELINE_DEADLINE[0]
    assert _milestones_due(first_target + 1, first_due) == [(first_due, first_target)]
    assert _milestones_due(first_target, first_due) == []
    last_due, _ = BASELINE_DEADLINE[-1]
    assert _milestones_due(1, last_due) == [BASELINE_DEADLINE[-1]]
    assert _milestones_due(0, last_due) == []


