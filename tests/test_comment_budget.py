def test_every_allowlist_anchor_is_long_enough_to_identify_one_comment(
    comments: list[Comment], allowlist: list[Entry]
) -> None:
    """Short anchors are how arm 3 gets defeated: match everything, review nothing."""
    by_identity = {(comment.path, comment.kind, comment.anchor) for comment in comments}
    short = [
        entry
        for entry in allowlist
        if len(entry.anchor) < MIN_ANCHOR_LENGTH
        and (entry.path, entry.kind, entry.anchor) not in by_identity
    ]
    formatted = "\n".join(f"  {entry.path} {entry.kind} '{entry.anchor}'" for entry in short[:20])
    assert not short, (
        f"{len(short)} anchor(s) are under {MIN_ANCHOR_LENGTH} characters and are not the "
        f"comment's whole normalised text:\n{formatted}"
    )
